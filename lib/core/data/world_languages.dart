/// Look up a [WorldLanguage] by its language code (falls back to English).
WorldLanguage getWorldLanguageByCode(String code) {
  final normalized = code.trim().toLowerCase();
  for (final lang in worldLanguages) {
    if (lang.code.toLowerCase() == normalized) {
      return lang;
    }
  }
  final base = normalized.split('-').first.split('_').first;
  for (final lang in worldLanguages) {
    if (lang.code.toLowerCase() == base) {
      return lang;
    }
  }
  return worldLanguages.first; // English
}

/// Returns all main official languages for a given ISO country code.
/// Every country in [countries] is guaranteed to return at least one language.
List<WorldLanguage> getOfficialLanguagesForCountry(String countryCode) {
  final upper = countryCode.trim().toUpperCase();
  final matches = worldLanguages
      .where((lang) => lang.countryCodes.contains(upper))
      .toList();
  if (matches.isNotEmpty) {
    // Sort so the most specific national language or primary official language appears first
    matches.sort(
      (a, b) => a.countryCodes.length.compareTo(b.countryCodes.length),
    );
    return matches;
  }
  return [worldLanguages.first];
}

/// Returns all countries where [language] is an official/national language.
List<Country> getCountriesForLanguage(WorldLanguage language) {
  final set = language.countryCodes.map((c) => c.toUpperCase()).toSet();
  return countries.where((c) => set.contains(c.code.toUpperCase())).toList();
}

/// Sorted list of all language names for profile spoken-language multi-select.
List<String> get allProfileLanguageOptionNames {
  final names = worldLanguages.map((l) => l.name).toSet().toList()..sort();
  if (!names.contains('Other')) {
    names.add('Other');
  }
  return names;
}
