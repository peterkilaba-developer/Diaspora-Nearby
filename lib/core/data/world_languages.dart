import 'package:diaspora_nearby/core/data/countries.dart';

/// Represents a main official or national language spoken in one or more
/// countries around the world.
class WorldLanguage {
  final String code;
  final String name;
  final String nativeName;
  final String primaryFlag;
  final bool isRtl;
  final List<String> countryCodes;

  const WorldLanguage({
    required this.code,
    required this.name,
    required this.nativeName,
    required this.primaryFlag,
    this.isRtl = false,
    required this.countryCodes,
  });

  /// Formatted label combining native and English name, e.g. "Kiswahili (Swahili)"
  String get displayLabel => nativeName.toLowerCase() == name.toLowerCase()
      ? name
      : '$nativeName ($name)';
}

