  static const _collection = 'real_estate_listings';
  static const _tag = 'mock_seed';

  /// Seeds all mock real estate listings (plots + farms + houses).
  /// Uses the authenticated user's UID so Firestore rules allow the write.
  static Future<void> seed(String userId, String userName) async {
    final fs = FirebaseFirestore.instance;
    final snap = await fs
        .collection(_collection)
        .where('tags', arrayContains: _tag)
        .limit(1)
        .get();
    if (snap.docs.isNotEmpty) {
      debugPrint('[RealEstateSeeder] Mock data already exists → skipping.');
      return;
    }

    final all = [
      ..._plots(userId, userName),
      ..._farms(userId, userName),
      ..._houses(userId, userName),
    ];
    final batch = fs.batch();
    for (final data in all) {
      batch.set(fs.collection(_collection).doc(), data);
    }
    await batch.commit();
    debugPrint('[RealEstateSeeder] Seeded ${all.length} real estate listings.');
  }

  /// Clears all mock-seeded real estate listings.
  static Future<void> clear() async {
    final fs = FirebaseFirestore.instance;
    final snap = await fs
        .collection(_collection)
        .where('tags', arrayContains: _tag)
        .get();
    if (snap.docs.isEmpty) return;
    final batch = fs.batch();
    for (final doc in snap.docs) {
      batch.delete(doc.reference);
    }
    await batch.commit();
    debugPrint('[RealEstateSeeder] Cleared ${snap.docs.length} mock listings.');
  }

