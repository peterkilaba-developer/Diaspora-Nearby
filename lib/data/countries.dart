Continent? getContinentByCountryCode(String countryCode) {
  final country = countries.firstWhere(
    (c) => c.code.toUpperCase() == countryCode.toUpperCase(),
    orElse: () => countries.first,
  );
  return country.continent;
}

bool hasStateLevelHierarchyFromData(String countryCode) {
  final country = countries.firstWhere(
    (c) => c.code.toUpperCase() == countryCode.toUpperCase(),
    orElse: () => countries.first,
  );
  return country.hasStateLevel;
}

String getStateTerminology(String countryCode) {
  final country = countries.firstWhere(
    (c) => c.code.toUpperCase() == countryCode.toUpperCase(),
    orElse: () => countries.first,
  );
  return country.stateTerminology ?? 'State';
}

Country? getCountryByCode(String countryCode) {
  try {
    return countries.firstWhere(
      (c) => c.code.toUpperCase() == countryCode.toUpperCase(),
    );
  } catch (e) {
    return null;
  }
}

