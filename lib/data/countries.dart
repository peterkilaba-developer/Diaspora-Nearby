enum Continent {
  africa('Africa'),
  asia('Asia'),
  europe('Europe'),
  northAmerica('North America'),
  southAmerica('South America'),
  oceania('Oceania'),
  antarctica('Antarctica'),
  caribbean('Caribbean');

  final String displayName;
  const Continent(this.displayName);
}

class Country {
  final String code;
  final String name;
  final String dialCode;
  final String flag;
  final Continent continent;
  final bool hasStateLevel;
  final String? stateTerminology;

  const Country({
    required this.code,
    required this.name,
    required this.dialCode,
    required this.flag,
    required this.continent,
    required this.hasStateLevel,
    this.stateTerminology,
  });
}

